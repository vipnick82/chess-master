#!/usr/bin/env python3
"""Build both versions of Chess Master from the shared sources.

  index.html             the phone app (PWA) served by GitHub Pages
  sw.js                  its offline cache, versioned by a hash of every file it serves
  dist-claude/index.html the page published as a Claude artifact (same scripts, fonts from Google, chess.js from cdnjs)

Run from anywhere:  python3 tools/build.py
"""
import hashlib, json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = (ROOT / "src" / "page.html").read_text(encoding="utf-8")

CDN_CHESS = "https://cdnjs.cloudflare.com/ajax/libs/chess.js/0.10.3/chess.min.js"
APP_SCRIPTS = ["data.js", "lessons.js", "core.js", "tasks.js", "smart.js", "assets.js", "views.js", "extras.js", "play.js"]
LAZY = ["pieces.js", "puzzles.json", "stockfish-19-lite-single.js", "stockfish-19-lite-single.wasm"]

# iPhone launch screens: (css width, css height, pixel ratio)
LAUNCH = [(430, 932, 3), (393, 852, 3), (390, 844, 3), (428, 926, 3), (375, 812, 3), (414, 896, 2)]


def split_page(page):
    """Head material (title, meta, links, style) and the body markup."""
    cut = page.index("</style>") + len("</style>")
    return page[:cut], page[cut:]


def build_pwa():
    head, body = split_page(SRC)
    head = re.sub(r'<meta name="claude:viewport-fit-sides"[^>]*>\n?', "", head)
    head = re.sub(r'<link rel="preconnect"[^>]*>\n?', "", head)
    head = re.sub(r'<link rel="stylesheet" href="https://fonts\.googleapis\.com[^>]*>\n?', '<link rel="stylesheet" href="fonts/fonts.css">\n', head)
    assert CDN_CHESS in body
    body = body.replace(f'<script src="{CDN_CHESS}"></script>', '<script src="pwa.js"></script>\n<script src="chess-0.10.3.js"></script>')
    launch = "\n".join(
        f'<link rel="apple-touch-startup-image" href="icons/launch-{w}x{h}@{r}x.png" '
        f'media="(device-width: {w}px) and (device-height: {h}px) and (-webkit-device-pixel-ratio: {r}) and (orientation: portrait)">'
        for w, h, r in LAUNCH)
    doc = f"""<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="Личен шахматен треньор: уроци, пъзели по слабите места, дебюти и игра със Stockfish.">
<meta name="theme-color" content="#262421">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Chess Master">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icons/favicon.svg" type="image/svg+xml">
<link rel="icon" href="icons/favicon-32.png" sizes="32x32" type="image/png">
<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">
{launch}
<style>
/* page frame: the same reset the Claude page gets, plus app-like touch behaviour */
:root{{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}}
html{{touch-action:manipulation;-webkit-text-size-adjust:100%}}
body{{margin:0;overscroll-behavior-y:none}}
img{{max-width:100%}}
</style>
{head}
</head>
<body>{body}
</body>
</html>
"""
    (ROOT / "index.html").write_text(doc, encoding="utf-8")


def build_sw():
    files = ["index.html", "manifest.webmanifest", "pwa.js", "chess-0.10.3.js"] + APP_SCRIPTS + LAZY
    files += sorted(str(p.relative_to(ROOT)) for p in (ROOT / "fonts").iterdir() if p.is_file())
    files += ["icons/favicon.svg", "icons/favicon-32.png", "icons/apple-touch-icon.png", "icons/icon-192.png", "icons/icon-512.png"]
    h = hashlib.sha1()
    for f in files:
        h.update(f.encode()); h.update((ROOT / f).read_bytes())
    version = "cm-" + h.hexdigest()[:12]
    assets = ["./"] + files
    sw = f"""/* Offline cache for Chess Master. Generated by tools/build.py: do not edit by hand. */
"use strict";
const VERSION = {json.dumps(version)};
const ASSETS = {json.dumps(assets, ensure_ascii=False)};
self.addEventListener("install", e => {{
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(ASSETS)).then(() => self.skipWaiting()));
}});
self.addEventListener("activate", e => {{
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith("cm-") && k !== VERSION).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
}});
self.addEventListener("fetch", e => {{
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === "navigate") {{
    e.respondWith(caches.match("./index.html").then(hit => hit || fetch(req)).catch(() => caches.match("./index.html")));
    return;
  }}
  e.respondWith(caches.open(VERSION).then(c => c.match(req, {{ignoreSearch: true}}).then(hit => hit || fetch(req).then(res => {{
    if (res && res.ok && res.type === "basic") c.put(req, res.clone());
    return res;
  }}))));
}});
"""
    (ROOT / "sw.js").write_text(sw, encoding="utf-8")
    return version, sum((ROOT / f).stat().st_size for f in files)


def build_claude():
    out = ROOT / "dist-claude"
    out.mkdir(exist_ok=True)
    (out / "index.html").write_text(SRC, encoding="utf-8")


if __name__ == "__main__":
    build_pwa()
    version, size = build_sw()
    build_claude()
    print(f"index.html, sw.js ({version}, {size/1e6:.1f} MB cached), dist-claude/index.html")
